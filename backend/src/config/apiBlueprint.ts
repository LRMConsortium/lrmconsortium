/**
 * The declared API contract.
 *
 * This file is deliberately free of Express and Mongoose imports. That is what
 * lets `npm run verify` assert against it without a server or a database, and
 * lets `npm run blueprint` render the human-readable reference from it. The
 * markdown in `docs/API-BLUEPRINT.md` is generated from here — so it cannot
 * drift from the declarations, and `assertBlueprintMatchesRouters()` (called at
 * boot outside production) catches drift between the declarations and what the
 * routers actually mounted.
 *
 * Which roles can call which endpoint is *computed* from `ROLE_DEFINITIONS`,
 * never written down. A hand-maintained access table is a lie waiting to happen.
 */

export type HttpMethod = 'GET' | 'POST' | 'PATCH' | 'PUT' | 'DELETE';

/** How a request is narrowed to the caller's own records. */
export type OwnershipRule =
  /** No narrowing — the resource is not owned by anyone. */
  | 'none'
  /** `BaseService.scopeFor()` narrows the query; `requireOwnership` guards :id. */
  | 'scoped'
  /** The record is resolved from the token, not from the URL. */
  | 'self';

export interface EndpointSpec {
  method: HttpMethod;
  /** Path relative to `API_PREFIX`, e.g. `/landlords/:id`. */
  path: string;
  module: string;
  summary: string;
  /** HQ zone gate, or `null` when the route carries no `enterZone`. */
  zone: HQZone | null;
  auth: 'required' | 'optional' | 'none';
  /** Any one of these grants is sufficient. Empty = authentication only. */
  permissions: PermissionGrant[];
  ownership: OwnershipRule;
  /** Zod schema name for the body, if any. */
  requestBody?: string;
  /** Zod schema name for the query string, if any. */
  requestQuery?: string;
  responseShape: string;
  /**
   * Component schema for the response payload. Set explicitly where the shape is
   * not a plain resource — parsing it out of `responseShape` prose works for the
   * generic CRUD surface but not for a dashboard or a rotation preview.
   */
  responseSchema?: string;
  /**
   * False for the handful of endpoints that return a raw document rather than
   * the `{ success, data }` envelope. Only `/openapi.json` today: a spec wrapped
   * in an envelope is not a spec any tool can read.
   */
  enveloped?: boolean;
  /**
   * `profile` = generated by `defineProfileModule`'s generic surface;
   * `custom`  = hand-mounted in the module's own router.
   */
  surface: 'profile' | 'custom';
  /** Rate-limit bucket beyond the global one. */
  rateLimit?: 'auth' | 'adServe';
  audited?: boolean;
  notes?: string;
}

/** Per-collection ownership wiring, mirroring each module's `serviceOptions`. */
export interface ScopeSpec {
  /** Field holding the owning `User` id. */
  ownerPath?: string;
  /** Field holding the owning organisation id. */
  organizationPath?: string;
  /** Plain-language statement of what a narrow-scoped caller sees. */
  describes: string;
}

export interface ProfileModuleSpec {
  module: string;
  /** Plural collection segment, e.g. `landlords`. */
  collectionPath: string;
  /** Singular item segment, e.g. `landlord`. */
  itemPath: string;
  /** Named id parameter, e.g. `landlordId`. */
  idParam: string;
  resource: Resource;
  adminZone: HQZone;
  memberZone: HQZone;
  verifiable: boolean;
  label: string;
  createSchema: string;
  updateSchema: string;
  scope: ScopeSpec;
}

