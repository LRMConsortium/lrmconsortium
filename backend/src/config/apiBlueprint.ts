/**
 * The eleven-route surface `defineProfileModule` mounts for every profile
 * collection. Kept here as a template so the blueprint states it once rather
 * than fourteen times, in the same order the router registers them.
 */
export function profileEndpoints(spec: ProfileModuleSpec): EndpointSpec[] {
  const p = (action: string): PermissionGrant => `${spec.resource}:${action}` as PermissionGrant;
  const coll = `/${spec.collectionPath}`;
  const item = `/${spec.itemPath}`;
  const id = `${item}/:${spec.idParam}`;
  const envelope = `{ success, data: ${spec.label} }`;

  const endpoints: Omit<EndpointSpec, 'surface'>[] = [
    {
      method: 'GET',
      path: `${item}/me`,
      module: spec.module,
      summary: `Read the caller's own ${spec.label.toLowerCase()}`,
      zone: spec.memberZone,
      auth: 'required',
      permissions: [p('readOwn')],
      ownership: 'self',
      responseShape: envelope,
      notes:
        'Record resolved from the token, never from the URL. Declared before the `:id` route — otherwise Express parses `me` as an id.',
    },
    {
      method: 'PATCH',
      path: `${item}/me`,
      module: spec.module,
      summary: `Update the caller's own ${spec.label.toLowerCase()}`,
      zone: spec.memberZone,
      auth: 'required',
      permissions: [p('updateOwn')],
      ownership: 'self',
      requestBody: spec.updateSchema,
      responseShape: envelope,
      audited: true,
    },
    {
      method: 'GET',
      path: coll,
      module: spec.module,
      summary: `List ${spec.label.toLowerCase()}s`,
      zone: spec.adminZone,
      auth: 'required',
      permissions: [p('read')],
      ownership: 'scoped',
      requestQuery: 'listQuery',
      responseShape: `{ success, data: ${spec.label}[], meta: PageMeta }`,
      audited: true,
    },
    {
      method: 'POST',
      path: coll,
      module: spec.module,
      summary: `Create a ${spec.label.toLowerCase()}`,
      zone: spec.adminZone,
      auth: 'required',
      permissions: [p('create')],
      ownership: 'none',
      requestBody: spec.createSchema,
      responseShape: envelope,
      audited: true,
    },
    {
      method: 'GET',
      path: id,
      module: spec.module,
      summary: `Read one ${spec.label.toLowerCase()}`,
      zone: spec.adminZone,
      auth: 'required',
      permissions: [p('read'), p('readOwn')],
      ownership: 'scoped',
      responseShape: envelope,
      audited: true,
    },
    {
      method: 'PATCH',
      path: id,
      module: spec.module,
      summary: `Update one ${spec.label.toLowerCase()}`,
      zone: spec.adminZone,
      auth: 'required',
      permissions: [p('update'), p('updateOwn')],
      ownership: 'scoped',
      requestBody: spec.updateSchema,
      responseShape: envelope,
      audited: true,
    },
  ];

  if (spec.verifiable) {
    endpoints.push({
      method: 'PATCH',
      path: `${id}/verify`,
      module: spec.module,
      summary: `Advance verification on a ${spec.label.toLowerCase()}`,
      zone: spec.adminZone,
      auth: 'required',
      permissions: [p('verify')],
      ownership: 'none',
      requestBody: 'verificationBody',
      responseShape: envelope,
      audited: true,
      notes: 'Back Office act. `verified` stamps verifiedAt/verifiedBy; `rejected` requires a note.',
    });
  }

  endpoints.push(
    {
      method: 'DELETE',
      path: id,
      module: spec.module,
      summary: `Archive a ${spec.label.toLowerCase()} (soft delete)`,
      zone: spec.adminZone,
      auth: 'required',
      permissions: [p('delete')],
      ownership: 'none',
      responseShape: '204 No Content',
      audited: true,
      notes: 'Sets deletedAt and status=archived. Nothing is removed from the collection.',
    },
    {
      method: 'POST',
      path: `${id}/restore`,
      module: spec.module,
      summary: `Restore an archived ${spec.label.toLowerCase()}`,
      zone: spec.adminZone,
      auth: 'required',
      permissions: [p('update')],
      ownership: 'none',
      responseShape: envelope,
      audited: true,
    },
  );

  return endpoints.map((e) => ({ ...e, surface: 'profile' as const }));
}

