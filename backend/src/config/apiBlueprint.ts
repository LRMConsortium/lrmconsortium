/** Endpoints marked Founder-only in prose are enforced by `requireFounder`. */
function isFounderOnly(ep: EndpointSpec): boolean {
  return ep.notes?.includes('Founder-only') ?? false;
}

/**
 * Can `role` reach `endpoint`? Applies the same three gates the middleware does:
 * zone membership, zone entry permissions, then the endpoint's own grants.
 */
export function roleCanReach(role: Role, endpoint: EndpointSpec): boolean {
  if (endpoint.auth === 'none') return true;
  if (isFounderOnly(endpoint) && role !== 'founder') return false;

  const definition = ROLE_DEFINITIONS[role];
  const grants = grantsForRoles([role]);

  if (endpoint.zone) {
    if (!definition.allowedZones.includes(endpoint.zone)) return false;
    const entry = HQ_ZONE_DEFINITIONS[endpoint.zone].entryPermissions;
    if (entry.length > 0 && !entry.some((p) => can(grants, p as Permission))) return false;
  }

  if (endpoint.permissions.length === 0) return true;
  return endpoint.permissions.some((p) => can(grants, p as Permission));
}

export function rolesFor(endpoint: EndpointSpec): Role[] {
  return ROLES.filter((r) => roleCanReach(r, endpoint));
}

/** The blueprint with its computed access list attached. */
export interface ResolvedEndpoint extends EndpointSpec {
  roles: Role[];
}

export function resolveBlueprint(): ResolvedEndpoint[] {
  return API_BLUEPRINT.map((ep) => ({ ...ep, roles: rolesFor(ep) }));
}

/** Group the contract by module, in declaration order. */
export function blueprintByModule(): { module: string; endpoints: ResolvedEndpoint[] }[] {
  const groups = new Map<string, ResolvedEndpoint[]>();
  for (const ep of resolveBlueprint()) {
    const list = groups.get(ep.module) ?? [];
    list.push(ep);
    groups.set(ep.module, list);
  }
  return [...groups.entries()].map(([module, endpoints]) => ({ module, endpoints }));
}

/** `GET /_blueprint` — what the caller can actually reach. */
export function blueprintForRole(role: Role | null): ResolvedEndpoint[] {
  const all = resolveBlueprint();
  if (!role) return all.filter((ep) => ep.auth === 'none');
  return all.filter((ep) => ep.roles.includes(role));
}

/**
 * A path is "static-first" safe when no literal segment is registered after a
 * parameter segment that would swallow it. `/drivers/verification-queue` must
 * come before `/drivers/:id`, or Express matches the id route and the literal
 * 404s (or 422s on the ObjectId validator).
 */
export function shadowedPaths(endpoints: EndpointSpec[] = API_BLUEPRINT): string[] {
  const problems: string[] = [];
  const byMethod = new Map<HttpMethod, EndpointSpec[]>();
  for (const ep of endpoints) {
    byMethod.set(ep.method, [...(byMethod.get(ep.method) ?? []), ep]);
  }

  for (const [, list] of byMethod) {
    list.forEach((ep, index) => {
      const segments = ep.path.split('/');
      const paramAt = segments.findIndex((s) => s.startsWith(':'));
      if (paramAt === -1) return;

      // Any literal path registered later that this param route would match.
      for (const later of list.slice(index + 1)) {
        const lSegments = later.path.split('/');
        if (lSegments.length !== segments.length) continue;
        const matches = segments.every(
          (s, i) => s.startsWith(':') || s === lSegments[i],
        );
        const laterIsLiteral = lSegments.every((s) => !s.startsWith(':'));
        if (matches && laterIsLiteral) {
          problems.push(`${ep.method} ${ep.path} (declared first) shadows ${later.path}`);
        }
      }
    });
  }
  return problems;
}
