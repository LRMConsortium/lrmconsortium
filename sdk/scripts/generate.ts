function generateRolesAndZones(): void {
  const roles = spec['x-roles-catalogue'];
  const zones = spec['x-hq-zones'];

  write(
    'types/roles.ts',
    banner('The fifteen platform roles, and the permission matcher.') +
      `export const ROLES = [\n${roles.map((r) => `  '${r}',`).join('\n')}\n] as const;\n\n` +
      `export type Role = (typeof ROLES)[number];\n\n` +
      `export function isRole(value: string): value is Role {\n  return (ROLES as readonly string[]).includes(value);\n}\n\n` +
      `/**\n * Mirrors the server's matcher, including \`*:*\`, \`resource:*\`, \`*:action\`,\n * and \`read\` implying \`readOwn\`. Used by the optional client-side guard —\n * never as a security boundary.\n */\nexport function can(grants: readonly string[], required: string): boolean {\n` +
      `  if (grants.includes('*:*') || grants.includes(required)) return true;\n` +
      `  const [resource, action] = required.split(':');\n` +
      `  if (grants.includes(\`\${resource}:*\`) || grants.includes(\`*:\${action}\`)) return true;\n` +
      `  const broader = action === 'readOwn' ? 'read' : action === 'updateOwn' ? 'update' : null;\n` +
      `  if (!broader) return false;\n` +
      `  return (\n    grants.includes(\`\${resource}:\${broader}\`) ||\n    grants.includes(\`\${resource}:*\`) ||\n    grants.includes(\`*:\${broader}\`)\n  );\n}\n`,
  );

  write(
    'types/zones.ts',
    banner('The five HQ zones and the three ad-serving zones.') +
      `export const HQ_ZONES = [\n${zones.map((z) => `  '${z.key}',`).join('\n')}\n] as const;\n\n` +
      `export type HQZone = (typeof HQ_ZONES)[number];\n\n` +
      `export const AD_ZONES = ['PUBLIC_PORTAL', 'MEMBER_PORTAL', 'USUSU_PORTAL'] as const;\n` +
      `export type AdZone = (typeof AD_ZONES)[number];\n\n` +
      `export interface HQZoneInfo {\n  code: string;\n  key: HQZone;\n  label: string;\n  purpose: string;\n}\n\n` +
      `export const HQ_ZONE_INFO: Record<HQZone, HQZoneInfo> = {\n` +
      zones
        .map(
          (z) =>
            `  ${z.key}: {\n    code: '${z.code}',\n    key: '${z.key}',\n    label: ${JSON.stringify(z.label)},\n    purpose: ${JSON.stringify(z.purpose)},\n  },`,
        )
        .join('\n') +
      `\n};\n\nexport function isHQZone(value: string): value is HQZone {\n  return (HQ_ZONES as readonly string[]).includes(value);\n}\n`,
  );
}

