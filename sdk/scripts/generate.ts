type Mode = 'response' | 'request';

/** Strip `writeOnly` from responses and `readOnly` from requests. */
function visible(prop: JsonSchema, mode: Mode): boolean {
  if (mode === 'response' && prop.writeOnly === true) return false;
  if (mode === 'request' && prop.readOnly === true) return false;
  return true;
}

/**
 * Two component schemas collide with types the hand-written runtime owns.
 * `PageMeta` is identical, so the runtime's wins and the generated one is
 * skipped. `HQZone` is *not* identical — the schema describes a zone object
 * while `types/zones.ts` exports the union of zone keys — so it is renamed
 * rather than dropped.
 */
const SKIP_SCHEMAS = new Set(['PageMeta']);
const RENAME_SCHEMAS: Record<string, string> = { HQZone: 'HQZoneDescriptor' };

function refName(ref: string): string {
  const raw = ref.replace('#/components/schemas/', '');
  if (raw === 'PageMeta') return 'PageMeta';
  return RENAME_SCHEMAS[raw] ?? raw;
}

/** Which schemas get an `Input` variant. Computed before rendering. */
const inputVariants = new Set<string>();

function tsName(name: string, mode: Mode): string {
  if (mode !== 'request') return name;
  return inputVariants.has(name) ? `${name}Input` : name;
}

function literal(value: unknown): string {
  return typeof value === 'string' ? JSON.stringify(value) : String(value);
}

function renderSchema(schema: JsonSchema | undefined, mode: Mode, depth = 0): string {
  if (!schema) return 'unknown';
  if (schema.$ref) return tsName(refName(schema.$ref), mode);

  if (schema.const !== undefined) return literal(schema.const);
  if (Array.isArray(schema.enum)) {
    return schema.enum.map(literal).join(' | ') || 'never';
  }

  if (Array.isArray(schema.allOf)) {
    const parts = schema.allOf.map((s: JsonSchema) => renderSchema(s, mode, depth));
    return parts.length === 1 ? parts[0]! : `(${parts.join(' & ')})`;
  }
  if (Array.isArray(schema.oneOf)) {
    return schema.oneOf.map((s: JsonSchema) => renderSchema(s, mode, depth)).join(' | ');
  }
  if (Array.isArray(schema.anyOf)) {
    return schema.anyOf.map((s: JsonSchema) => renderSchema(s, mode, depth)).join(' | ');
  }

  const nullable = schema.nullable === true ? ' | null' : '';

  switch (schema.type) {
    case 'string':
      return `string${nullable}`;
    case 'number':
    case 'integer':
      return `number${nullable}`;
    case 'boolean':
      return `boolean${nullable}`;
    case 'array':
      return `${renderSchema(schema.items, mode, depth)}[]${nullable}`;
    case 'object':
    default: {
      if (schema.additionalProperties && typeof schema.additionalProperties === 'object') {
        return `Record<string, ${renderSchema(schema.additionalProperties, mode, depth)}>${nullable}`;
      }
      const props = schema.properties as Record<string, JsonSchema> | undefined;
      if (!props) return `Record<string, unknown>${nullable}`;

      const required = new Set<string>((schema.required as string[]) ?? []);
      const pad = '  '.repeat(depth + 1);
      const lines: string[] = [];

      for (const [key, prop] of Object.entries(props)) {
        if (!visible(prop, mode)) continue;
        const optional = required.has(key) && visible(prop, mode) ? '' : '?';
        const doc = prop.description ? `${pad}/** ${String(prop.description).replace(/\*\//g, '*\\/')} */\n` : '';
        const safeKey = /^[A-Za-z_$][A-Za-z0-9_$]*$/.test(key) ? key : JSON.stringify(key);
        lines.push(`${doc}${pad}${safeKey}${optional}: ${renderSchema(prop, mode, depth + 1)};`);
      }

      if (lines.length === 0) return `Record<string, never>${nullable}`;
      return `{\n${lines.join('\n')}\n${'  '.repeat(depth)}}${nullable}`;
    }
  }
}

/** Does a schema (following $refs) contain any writeOnly/readOnly field? */
function hasMode(schema: JsonSchema, kind: 'writeOnly' | 'readOnly', seen = new Set<string>()): boolean {
  if (!schema || typeof schema !== 'object') return false;
  if (schema.$ref) {
    const name = refName(schema.$ref);
    if (seen.has(name)) return false;
    seen.add(name);
    return hasMode(spec.components.schemas[name]!, kind, seen);
  }
  if (schema[kind] === true) return true;
  for (const part of (schema.allOf ?? []) as JsonSchema[]) if (hasMode(part, kind, seen)) return true;
  for (const prop of Object.values((schema.properties ?? {}) as Record<string, JsonSchema>)) {
    if (hasMode(prop, kind, seen)) return true;
  }
  if (schema.items && hasMode(schema.items as JsonSchema, kind, seen)) return true;
  return false;
}

function generateTypes(): { emittedInputs: Set<string> } {
  const schemas = spec.components.schemas;
  const emittedInputs = new Set<string>();
  const chunks: string[] = [];

  // First pass: decide which schemas need an Input variant, so a `$ref` in
  // request position resolves to a name that will actually exist.
  // A spec that already declares `XInput` has said what the request shape is more
  // precisely than stripping `readOnly` off `X` ever could. Deriving one anyway
  // emits the same name twice. The declaration wins.
  const declared = new Set(Object.keys(schemas).map((n) => RENAME_SCHEMAS[n] ?? n));
  for (const [name, schema] of Object.entries(schemas)) {
    if (SKIP_SCHEMAS.has(name)) continue;
    const resolved = RENAME_SCHEMAS[name] ?? name;
    if (declared.has(`${resolved}Input`)) continue;
    if (hasMode(schema, 'readOnly')) inputVariants.add(resolved);
  }

  chunks.push(banner('All OpenAPI component schemas as TypeScript types.'));
  chunks.push(
    `/**\n * Two variants exist wherever the API distinguishes them:\n *\n *   \`Landlord\`       — a response. \`writeOnly\` fields (ID numbers, payout\n *                     details, security notes) are absent, because the server\n *                     never returns them.\n *   \`LandlordInput\`  — a request. \`readOnly\` fields (verification status,\n *                     counters, timestamps) are absent, because the server\n *                     owns them.\n *\n * Where a schema has neither, only the plain name is emitted.\n */\n\n`,
  );

  const names = Object.keys(schemas).sort();

  chunks.push(
    `import type { PageMeta } from './envelope.js';\n\nexport type { PageMeta };\n\n`,
  );

  for (const rawName of names) {
    if (SKIP_SCHEMAS.has(rawName)) continue;
    const name = RENAME_SCHEMAS[rawName] ?? rawName;
    const schema = schemas[rawName]!;
    const doc = schema.description
      ? `/** ${String(schema.description).replace(/\*\//g, '*\\/')} */\n`
      : '';
    // A schema whose every field is `writeOnly` has no response representation
    // at all — rendering it in response mode empties it to `Record<string,
    // never>`, and a client would be unable to build the body. That is not a
    // response type; render it as the request it is.
    const responseBody = renderSchema(schema, 'response');
    const requestBody = renderSchema(schema, 'request');
    const requestOnly =
      responseBody.startsWith('Record<string, never>') && !requestBody.startsWith('Record<string, never>');
    const body = requestOnly ? requestBody : responseBody;
    const keyword = body.startsWith('{') ? 'interface' : 'type';
    chunks.push(
      keyword === 'interface'
        ? `${doc}export interface ${name} ${body}\n\n`
        : `${doc}export type ${name} = ${body};\n\n`,
    );

    // An Input variant is only worth emitting when it differs — and never for a
    // schema already rendered as its request form.
    if (inputVariants.has(name) && !requestOnly) {
      const inputBody = renderSchema(schema, 'request');
      const inputKeyword = inputBody.startsWith('{') ? 'interface' : 'type';
      emittedInputs.add(name);
      chunks.push(
        inputKeyword === 'interface'
          ? `/** Request variant of \`${name}\` — server-controlled fields removed. */\nexport interface ${name}Input ${inputBody}\n\n`
          : `/** Request variant of \`${name}\`. */\nexport type ${name}Input = ${inputBody};\n\n`,
      );
    }
  }

  write('types/index.ts', chunks.join(''));
  return { emittedInputs };
}

