/**
 * Generates the typed surface of the SDK from `backend/docs/openapi.json`.
 *
 *   npm run generate
 *
 * Emits: src/types/index.ts, src/types/roles.ts, src/types/zones.ts,
 *        src/modules/*.ts, src/modules/index.ts
 *
 * Everything here is derived. The hand-written half of the SDK is the runtime —
 * clients, envelope, errors, pagination — which is the part that encodes
 * judgement. The 179 operations and 77 schemas are mechanical, and mechanical
 * things should be generated so they cannot drift from the server.
 */

import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';

const SPEC = resolve(process.cwd(), '../backend/docs/openapi.json');
const SRC = resolve(process.cwd(), 'src');

interface Op {
  operationId: string;
  summary?: string;
  description?: string;
  tags: string[];
  'x-zone': string | null;
  'x-roles': string[];
  'x-permissions': string[];
  'x-ownership': 'none' | 'scoped' | 'self';
  security?: unknown[];
  parameters?: { name: string; in: string; required?: boolean; schema?: JsonSchema }[];
  requestBody?: { required?: boolean; content: Record<string, { schema: { $ref?: string } }> };
  responses: Record<string, { content?: Record<string, { schema?: JsonSchema }> }>;
}

type JsonSchema = Record<string, any>;

const spec = JSON.parse(readFileSync(SPEC, 'utf8')) as {
  paths: Record<string, Record<string, Op>>;
  components: { schemas: Record<string, JsonSchema> };
  'x-hq-zones': { code: string; key: string; label: string; purpose: string }[];
  'x-roles-catalogue': string[];
};

const banner = (what: string): string =>
  `/**\n * ${what}\n *\n * GENERATED by \`npm run generate\` from backend/docs/openapi.json.\n * Do not edit — change the API, regenerate.\n */\n\n`;

function write(relative: string, contents: string): void {
  const out = resolve(SRC, relative);
  mkdirSync(dirname(out), { recursive: true });
  writeFileSync(out, contents, 'utf8');
}

