function methodName(method: string, path: string, collection: string, item: string): string {
  const key = `${method} ${path}`;
  if (NAME_OVERRIDES[key]) return NAME_OVERRIDES[key]!;

  const isCollection = path === `/${collection}`;
  const isItem = /^\/[^/]+\/\{[^}]+\}$/.test(path) && path.startsWith(`/${item}/`);
  const isMe = path === `/${item}/me`;

  if (isCollection && method === 'GET') return 'list';
  if (isCollection && method === 'POST') return 'create';
  if (isMe && method === 'GET') return 'me';
  if (isMe && method === 'PATCH') return 'updateMe';
  if (isItem && method === 'GET') return 'getById';
  if (isItem && method === 'PATCH') return 'update';
  if (isItem && method === 'DELETE') return 'delete';
  if (path.endsWith('/verify')) return 'verify';
  if (path.endsWith('/restore')) return 'restore';

  const tail = path
    .split('/')
    .filter((s) => s && !s.startsWith('{'))
    .slice(1)
    .join('-');
  return camel(tail || method.toLowerCase());
}

interface ModuleOp {
  method: string;
  path: string;
  op: Op;
  fn: string;
}

/**
 * OpenAPI encodes optional auth as an empty requirement object alongside the
 * real one. Read all three cases, or every anonymous endpoint looks required.
 */
function authOf(op: Op): 'none' | 'optional' | 'required' {
  const security = (op.security ?? []) as Record<string, unknown>[];
  if (security.length === 0) return 'none';
  if (security.some((s) => Object.keys(s).length === 0)) return 'optional';
  return 'required';
}

function requestTypeFor(op: Op, emittedInputs: Set<string>): string | null {
  const ref = op.requestBody?.content?.['application/json']?.schema?.$ref;
  if (!ref) return null;
  const name = refName(ref);
  return emittedInputs.has(name) ? `${name}Input` : name;
}

/**
 * A `$ref` to a component that is itself an array of another component.
 *
 * `LeaseList` is `Lease[]`, and a caller wants `Page<Lease>`, not `Page<Lease[]>`.
 * Named list schemas keep the spec readable; unwrapping them here keeps the
 * generated signatures honest.
 */
function arrayItemFor(name: string): string | null {
  const schema = spec.components.schemas[name] as JsonSchema | undefined;
  if (!schema || schema.type !== 'array') return null;
  const items = schema.items as JsonSchema | undefined;
  return items?.$ref ? refName(items.$ref) : null;
}

function responseTypeFor(op: Op): string {
  const success = Object.entries(op.responses).find(([code]) => code.startsWith('2'));
  if (!success) return 'void';
  const [code, response] = success;
  if (code === '204') return 'void';

  const schema = response.content?.['application/json']?.schema;
  if (!schema) return 'void';
  if (schema.$ref) return refName(schema.$ref);

  const data = schema.properties?.data as JsonSchema | undefined;
  if (!data) return 'void';
  if (data.$ref) {
    const name = refName(data.$ref);
    const item = arrayItemFor(name);
    return item ? `${item}[]` : name;
  }
  if (data.type === 'array' && data.items?.$ref) return `${refName(data.items.$ref)}[]`;
  return 'unknown';
}

function isPaginated(op: Op): boolean {
  const success = Object.entries(op.responses).find(([code]) => code.startsWith('2'));
  const schema = success?.[1]?.content?.['application/json']?.schema;
  return Boolean(schema?.properties?.meta);
}

function generateModules(emittedInputs: Set<string>): {
  modules: string[];
  operationCount: number;
} {
  const grouped = new Map<string, ModuleOp[]>();

  for (const [path, methods] of Object.entries(spec.paths)) {
    for (const [method, op] of Object.entries(methods)) {
      const mod = moduleFor(op.tags[0]!, path);
      const list = grouped.get(mod) ?? [];
      list.push({ method: method.toUpperCase(), path, op, fn: '' });
      grouped.set(mod, list);
    }
  }

  let operationCount = 0;
  const moduleNames = [...grouped.keys()].sort();

  for (const mod of moduleNames) {
    const ops = grouped.get(mod)!;

    // Derive the collection/item segment pair from the paths in this module.
    const collection = ops.map((o) => o.path.slice(1)).find((p) => !p.includes('/') && !p.includes('{')) ?? mod;
    const item =
      ops
        .map((o) => o.path.split('/')[1] ?? '')
        .find((s) => s && s !== collection && !s.startsWith('{')) ?? collection;

    const used = new Set<string>();
    for (const entry of ops) {
      let name = methodName(entry.method, entry.path, collection, item);
      let n = 2;
      while (used.has(name)) name = `${name}${n++}`;
      used.add(name);
      entry.fn = name;
    }

    ops.sort((a, b) => a.fn.localeCompare(b.fn));

    const typeImports = new Set<string>();
    const bodyLines: string[] = [];

    for (const { method, path, op, fn } of ops) {
      operationCount += 1;
      const reqType = requestTypeFor(op, emittedInputs);
      const resType = responseTypeFor(op);
      if (reqType) typeImports.add(reqType);
      const bare = resType.replace(/\[\]$/, '');
      if (bare !== 'void' && bare !== 'unknown') typeImports.add(bare);

      const pathParams = [...path.matchAll(/\{([^}]+)\}/g)].map((m) => m[1]!);
      const args: string[] = pathParams.map((p) => `${p}: string`);
      if (reqType) args.push(`body: ${reqType}`);
      const paginated = isPaginated(op);
      args.push(paginated ? 'options?: ListOptions' : 'options?: RequestOptions');

      const template = path.replace(/\{([^}]+)\}/g, (_m, p: string) => `\${seg(${p})}`);
      const target = template.includes('${') ? `\`${template}\`` : `'${path}'`;

      const metaLiteral =
        `{ operationId: '${op.operationId}', method: '${method}', pathTemplate: '${path}', ` +
        `zone: ${op['x-zone'] ? `'${op['x-zone']}'` : 'null'}, ` +
        `roles: ${JSON.stringify(op['x-roles'])}, ` +
        `permissions: ${JSON.stringify(op['x-permissions'])}, ` +
        `ownership: '${op['x-ownership']}', ` +
        `auth: '${authOf(op)}' }`;

      const call = paginated
        ? `client().list<${resType.replace(/\[\]$/, '')}>(${target}, withMeta(options, META.${fn}))`
        : method === 'GET'
          ? `client().get<${resType}>(${target}, withMeta(options, META.${fn}))`
          : method === 'DELETE'
            ? `client().delete<${resType}>(${target}, withMeta(options, META.${fn}))`
            : `client().${method.toLowerCase()}<${resType}>(${target}, ${reqType ? 'body' : 'undefined'}, withMeta(options, META.${fn}))`;

      const returnType = paginated
        ? `Promise<Page<${resType.replace(/\[\]$/, '')}>>`
        : `Promise<${resType}>`;

      const docLines = [
        op.summary ?? null,
        op.description ? `\n   * ${op.description}` : null,
        '',
        `\`${method} ${path}\``,
        `Zone: ${op['x-zone'] ?? '—'}`,
        `Roles: ${op['x-roles'].length ? op['x-roles'].join(', ') : 'anyone'}`,
        op['x-permissions'].length ? `Permission: ${op['x-permissions'].join(' | ')}` : null,
        `Ownership: ${op['x-ownership']}`,
      ]
        .filter((l) => l !== null)
        .map((l) => (l === '' ? '   *' : `   * ${l}`));

      bodyLines.push(
        `  /**\n${docLines.join('\n')}\n   */\n  ${fn}(${args.join(', ')}): ${returnType} {\n    return ${call};\n  },\n`,
      );
    }

    const metaEntries = ops
      .map(({ method, path, op, fn }) => {
        return (
          `  ${fn}: { operationId: '${op.operationId}', method: '${method}' as const, pathTemplate: '${path}', ` +
          `zone: ${op['x-zone'] ? `'${op['x-zone']}' as const` : 'null'}, ` +
          `roles: ${JSON.stringify(op['x-roles'])} as Role[], ` +
          `permissions: ${JSON.stringify(op['x-permissions'])}, ` +
          `ownership: '${op['x-ownership']}' as const, ` +
          `auth: '${authOf(op)}' as const },`
        );
      })
      .join('\n');

    const imports = [...typeImports].sort();
    const contents =
      banner(`\`${mod}\` — ${ops.length} operation${ops.length === 1 ? '' : 's'}.`) +
      `import { seg } from '../client/ApiClient.js';\n` +
      `import type { OperationMeta } from '../client/types.js';\n` +
      `import type { Page } from '../types/pagination.js';\n` +
      `import type { Role } from '../types/roles.js';\n` +
      (imports.length ? `import type {\n${imports.map((i) => `  ${i},`).join('\n')}\n} from '../types/index.js';\n` : '') +
      `import { client, withMeta, type ListOptions, type RequestOptions } from './_runtime.js';\n\n` +
      `/** Zone, roles and permissions for each operation, straight from the spec. */\n` +
      `export const META = {\n${metaEntries}\n} satisfies Record<string, OperationMeta>;\n\n` +
      `export const ${identFor(mod)} = {\n${bodyLines.join('\n')}};\n\n` +
      `export type ${mod[0]!.toUpperCase()}${mod.slice(1)}Api = typeof ${identFor(mod)};\n`;

    write(`modules/${mod}.ts`, contents);
  }

  // Shared plumbing for the generated modules.
  write(
    'modules/_runtime.ts',
    banner('Shared plumbing for the generated modules.') +
      `import type { ApiClient, RequestOptions as BaseRequestOptions } from '../client/ApiClient.js';\n` +
      `import type { OperationMeta, QueryParams } from '../client/types.js';\n` +
      `import type { ListQuery } from '../types/pagination.js';\n` +
      `import { LrmcApiError } from '../types/errors.js';\n\n` +
      `export type RequestOptions = BaseRequestOptions;\n` +
      `export interface ListOptions extends BaseRequestOptions {\n  query?: ListQuery & QueryParams;\n}\n\n` +
      `let current: ApiClient | null = null;\n\n` +
      `/** Set by \`configureApi()\`. Modules resolve it lazily, per call. */\n` +
      `export function setClient(instance: ApiClient | null): void {\n  current = instance;\n}\n\n` +
      `export function client(): ApiClient {\n` +
      `  if (!current) {\n` +
      `    throw new LrmcApiError({\n` +
      `      code: 'CONFIGURATION_ERROR',\n` +
      `      message:\n` +
      `        'SDK not configured. Call configureApi({ baseUrl, token }) before using any module.',\n` +
      `    });\n  }\n  return current;\n}\n\n` +
      `export function hasClient(): boolean {\n  return current !== null;\n}\n\n` +
      `/** Attach operation metadata so the optional RBAC guard can read it. */\n` +
      `export function withMeta(\n  options: BaseRequestOptions | undefined,\n  meta: OperationMeta,\n): BaseRequestOptions {\n  return { ...options, meta };\n}\n`,
  );

  // The barrel.
  write(
    'modules/index.ts',
    banner('Every module, and the aggregate `api` surface.') +
      moduleNames.map((m) => `import { ${identFor(m)} } from './${m}.js';`).join('\n') +
      '\n\n' +
      moduleNames
        .map(
          (m) =>
            `export { ${identFor(m)}, META as ${m}Meta, type ${m[0]!.toUpperCase()}${m.slice(1)}Api } from './${m}.js';`,
        )
        .join('\n') +
      '\n\n' +
      `/**\n * The whole API, grouped by module.\n *\n *   import { api } from '@lrmc/sdk';\n *   const page = await api.landlords.list();\n */\nexport const api = {\n` +
      moduleNames
        .map((m) => (identFor(m) === m ? `  ${m},` : `  ${m}: ${identFor(m)},`))
        .join('\n') +
      `\n} as const;\n\nexport type Api = typeof api;\n`,
  );

  return { modules: moduleNames, operationCount };
}

