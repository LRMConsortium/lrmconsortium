/**
 * Which SDK module an operation belongs to. Mostly the OpenAPI tag, but three
 * tags are split so the package matches the requested file layout.
 */
function moduleFor(tag: string, path: string): string {
  if (tag === 'advertising') return path.startsWith('/ad-policy') ? 'adPolicy' : 'ads';
  if (tag === 'auth') {
    return path === '/auth/roles' || path === '/auth/resolve' || path.endsWith('/roles')
      ? 'rbac'
      : 'auth';
  }
  if (tag === 'platform') return 'blueprint';
  if (tag === 'publicPortal') return 'public';
  if (tag === 'backOfficeStaff') return 'staff';
  if (tag === 'property') return 'properties';
  if (tag === 'advertiser') return 'advertisers';
  // Profile tags are singular in the spec; the SDK files are plural.
  const plural: Record<string, string> = {
    founder: 'founders',
    hqExecutive: 'hqExecutives',
    coordinator: 'coordinators',
    vendor: 'vendors',
    landlord: 'landlords',
    tenant: 'tenants',
    driver: 'drivers',
    rider: 'riders',
    airbnbHost: 'airbnbHosts',
    hotel: 'hotels',
    resort: 'resorts',
    rentalCarCompany: 'rentalCarCompanies',
    hq: 'hq',
    // Operational surfaces. `maintenance` and `commercialClient` are named for
    // the collection they address, not for the tag.
    lease: 'leases',
    maintenance: 'maintenanceRequests',
    ride: 'rides',
    payment: 'payments',
    notification: 'notifications',
    commercialClient: 'commercialClients',
    payout: 'payoutBatches',
    document: 'documents',
    fac: 'fac',
    governance: 'governance',
  };
  return plural[tag] ?? tag;
}

/**
 * `public` is a reserved word, so it cannot be a bare import binding or a `const`
 * name. The file and the `api.public` key keep the requested name; only the
 * internal identifier differs.
 */
const RESERVED = new Set(['public', 'private', 'protected', 'package', 'static', 'delete', 'new']);

function identFor(moduleName: string): string {
  return RESERVED.has(moduleName) ? `${moduleName}Api` : moduleName;
}

function camel(input: string): string {
  return input
    .replace(/[{}]/g, '')
    .split(/[-_/]/)
    .filter(Boolean)
    .map((w, i) => (i === 0 ? w[0]!.toLowerCase() + w.slice(1) : w[0]!.toUpperCase() + w.slice(1)))
    .join('');
}

